"""Generate stable request references from core OpenAPI and MCP source signatures."""

from __future__ import annotations

import argparse
import ast
import json
import os
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def cell(value):
    return str(value).replace("|", r"\|").replace("\n", " ")


def kind(schema):
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "enum" in schema:
        return ", ".join(json.dumps(x) for x in schema["enum"])
    if "anyOf" in schema:
        return " or ".join(kind(x) for x in schema["anyOf"])
    if schema.get("type") == "array":
        return "array of " + kind(schema.get("items", {}))
    return schema.get("type", "value")


def bounds(schema):
    names = [
        "minimum",
        "maximum",
        "exclusiveMinimum",
        "exclusiveMaximum",
        "minLength",
        "maxLength",
        "minItems",
        "maxItems",
        "pattern",
    ]
    parts = [f"{name}={schema[name]}" for name in names if name in schema]
    for variant in schema.get("anyOf", []):
        detail = bounds(variant)
        if detail:
            parts.append(detail)
    return "; ".join(parts)


def http_reference(schema):
    lines = [
        "# HTTP request reference",
        "",
        "Generated by `python scripts/docs_reference.py` from the core OpenAPI models.",
        "Use [the API guide](API.md) for response semantics and workflows. Unknown body",
        "fields are rejected; cross-field validators can impose additional constraints.",
        "Framework `/docs` and `/openapi.json` routes are available separately.",
        "",
        "## Routes",
        "",
        "| Method and path | Request body | Query parameters |",
        "|---|---|---|",
    ]
    for path, methods in sorted(schema["paths"].items()):
        for method, op in sorted(methods.items()):
            body = op.get("requestBody", {}).get("content", {}).get("application/json", {})
            fields = (
                ", ".join(p["name"] for p in op.get("parameters", []) if p.get("in") == "query")
                or "—"
            )
            lines.append(
                f"| `{method.upper()} {path}` | {cell(kind(body['schema'])) if body else '—'} | "
                f"{cell(fields)} |"
            )
    for path, methods in sorted(schema["paths"].items()):
        for method, op in sorted(methods.items()):
            params = [p for p in op.get("parameters", []) if p.get("in") == "query"]
            if not params:
                continue
            lines += [
                "",
                f"## {method.upper()} {path}",
                "",
                "| Query field | Type/choices | Required/default | Bounds |",
                "|---|---|---|---|",
            ]
            for param in params:
                data = param["schema"]
                default = "required" if param.get("required") else json.dumps(data.get("default"))
                lines.append(
                    f"| `{param['name']}` | {cell(kind(data))} | {cell(default)} | "
                    f"{cell(bounds(data))} |"
                )
    for name, model in sorted(schema["components"]["schemas"].items()):
        if name in {"HTTPValidationError", "ValidationError"}:
            continue
        lines += [
            "",
            "## " + name,
            "",
            "| Field | Type/choices | Required/default | Bounds |",
            "|---|---|---|---|",
        ]
        for field, data in model.get("properties", {}).items():
            default = (
                "required"
                if field in model.get("required", [])
                else json.dumps(data["default"], ensure_ascii=False)
                if "default" in data
                else "factory/default; see runtime schema"
            )
            lines.append(
                f"| `{field}` | {cell(kind(data))} | {cell(default)} | {cell(bounds(data))} |"
            )
    lines += ["", "[Documentation home](README.md) · [API guide](API.md)", ""]
    return "\n".join(lines)


def mcp_reference():
    tree = ast.parse((ROOT / "adapters/mcp_server.py").read_text())
    tools = [
        n
        for n in tree.body
        if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))
        and any(
            isinstance(d, ast.Call)
            and isinstance(d.func, ast.Attribute)
            and isinstance(d.func.value, ast.Name)
            and d.func.value.id == "mcp"
            and d.func.attr == "tool"
            for d in n.decorator_list
        )
    ]
    lines = [
        "# MCP tool reference",
        "",
        "Generated from the adapter tool signatures. The connected server's",
        "`tools/list` schemas are authoritative for runtime validation. Selected numeric",
        "controls are additionally bounded/clamped by adapter/backend code.",
        "Unknown tool arguments are rejected. Caller identity and public-target policy",
        "are injected by the adapter; they are not caller-selectable tool arguments.",
        "",
        f"This adapter registers **{len(tools)} tools**. "
        "See [agent integration](AGENT-UPGRADES.md)",
        "for the autonomous workflow and [public access](PUBLIC-ACCESS.md) for setup.",
        "",
    ]
    for node in tools:
        lines += [
            "## " + node.name,
            "",
            (ast.get_docstring(node) or "").split("\n\n")[0],
            "",
            "| Argument | Type/choices | Required/default |",
            "|---|---|---|",
        ]
        defaults = [None] * (len(node.args.args) - len(node.args.defaults)) + node.args.defaults
        for arg, default in zip(node.args.args, defaults):
            typ = ast.unparse(arg.annotation) if arg.annotation else "value"
            value = "required" if default is None else ast.unparse(default)
            lines.append(f"| `{arg.arg}` | {cell(typ)} | {cell(value)} |")
    lines += ["", "[Documentation home](README.md) · [Agent integration](AGENT-UPGRADES.md)", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix="dethrottled-docs-") as directory:
        os.environ["DETHROTTLED_DATA_DIR"] = directory
        sys.path.insert(0, str(ROOT / "src"))
        from dethrottled.server import app

        outputs = {
            "HTTP-REFERENCE.md": http_reference(app.openapi()),
            "MCP-REFERENCE.md": mcp_reference(),
        }
    changed = []
    for name, value in outputs.items():
        path = ROOT / "docs" / name
        if args.check:
            if not path.exists() or path.read_text() != value:
                changed.append(name)
        else:
            path.write_text(value)
    if changed:
        raise SystemExit(
            "Stale references: " + ", ".join(changed) + "; run scripts/docs_reference.py"
        )
    print("Request references match source" if args.check else "Generated HTTP and MCP references")


if __name__ == "__main__":
    main()
